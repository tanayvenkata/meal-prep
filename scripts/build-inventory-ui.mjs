import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const base = new URL("../src/mcp/inventory-ui/", import.meta.url);
const result = await build({
  entryPoints: [new URL("app.ts", base).pathname], bundle: true, write: false,
  format: "esm", platform: "browser", target: "es2020", minify: true,
  // The SDK debug logger includes tool payloads; do not ship it in the UI.
  drop: ["console", "debugger"], legalComments: "inline",
});
const js = result.outputFiles[0].text.replaceAll("</script", "<\\/script");
const html = (await readFile(new URL("template.html", base), "utf8")).replace("/* MISE_APP */", () => js);
const hash = createHash("sha256").update(html).digest("hex").slice(0, 16);
await writeFile(new URL("generated.ts", base), `// Generated by scripts/build-inventory-ui.mjs; do not edit.\nexport const inventoryResourceUri = ${JSON.stringify(`ui://mise/saved-kitchen-${hash}.html`)};\nexport const inventoryHtml = ${JSON.stringify(html)};\n`);
console.log(`Built saved kitchen UI (${Buffer.byteLength(html)} bytes, ${hash}).`);
